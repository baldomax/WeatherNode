def main() -> None:
    total_keys = len(new_keys)
    print(f"Total new keys to add: {total_keys}")
    print(f"Processing {len(FILES)} language files...\n")

    for filename in FILES:
        locale = filename.removesuffix(".json")
        filepath = LANG_DIR / filename

        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)

        added = 0
        for key, translations in new_keys.items():
            if key not in data:
                if locale in translations:
                    data[key] = translations[locale]
                    added += 1
                else:
                    print(f"  WARNING: No translation for key '{key}' in locale '{locale}'")

        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=4, sort_keys=True)
            f.write("\n")  # trailing newline

        print(f"{filename}: {added} keys added (of {total_keys})")

    print("\nDone.")


if __name__ == "__main__":
    main()
